#!/usr/bin/env python3
"""Round 7 (post hoc): 24 h runs at 10N 68E, launch intent as built and launch default.
Writes macros_long.tex and tables/table_long_rows.tex (rows inlined into Table VIII by analyze_r5.py)."""
import csv, glob, math, os
import numpy as np
from scipy import stats
H = os.path.dirname(os.path.abspath(__file__)); PD = os.path.dirname(H); TAB = os.path.join(PD, "tables")
M = {}
def mac(k, v, f="{:.2f}"):
    if isinstance(v, str): M[k] = v; return
    s = f.format(v); M[k + "Abs"] = f.replace("+", "").format(abs(v))
    if s.startswith("-"): s = "\\ensuremath{-}" + s[1:] if any(c in "123456789" for c in s) else s[1:]
    M[k] = s
def rd(p):
    o = {}
    for d in sorted(glob.glob(p + "/seed*")):
        if d.endswith(".tmp"): continue
        r = next(csv.DictReader(open(d + "/dataplane.csv"))); S = next(csv.DictReader(open(d + "/summary.csv")))
        ou = list(csv.DictReader(open(d + "/outages.csv"))); sv = float(S["served_s"])
        nc = [(float(x["start"]), float(x["dur"])) for x in ou if int(x["kind"]) in (0, 3)]
        o[int(d.split("seed")[-1])] = dict(crit=100 * float(r["crit_ratio"]), be=100 * float(r["be_share"]), av=float(S["feeder_avail"]),
            sha=S["binary_sha"], nc=100 * sum(x[1] for x in nc) / sv,
            nc1=100 * sum(x[1] for x in nc if x[0] < 3600) / 3600, nclate=100 * sum(x[1] for x in nc if x[0] >= 3600) / (sv - 3600))
    return o
def ci(x):
    x = np.asarray(x, float); return float(x.mean()), float(stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / math.sqrt(len(x)))
def dif(A, B, k):
    s = sorted(set(A) & set(B)); return np.array([A[i][k] - B[i][k] for i in s])
def sg(x, nd=2):
    t = f"{x:+.{nd}f}"; return f"{0:.{nd}f}" if float(t) == 0 else t.replace("-", "$-$")
def cell(x, nd=2):
    m, h = ci(x); return f"{sg(m, nd)}$\\pm${h:.{nd}f}"
def rule(x, thr):
    m, h = ci(x); return m <= -thr and m + h < 0 and (x < 0).sum() >= 0.8 * len(x)
K = 8.8; rows = []; shas = set(); n = 0
for T, tn in [(15, "Fifteen"), (30, "Thirty")]:
    R = {lab: {a: rd(f"{H}/runs/r7/long_{lab}_lo_ta{T}/{a}") for a in ("control", "hold")} for lab in ("asbuilt", "launch")}
    for lab in R:
        for X in R[lab].values(): shas |= {x["sha"] for x in X.values()}; n += len(X)
    for lab, ln in (("asbuilt", "Ab"), ("launch", "Ld")):
        c = dif(R[lab]["hold"], R[lab]["control"], "crit"); b = dif(R[lab]["hold"], R[lab]["control"], "be")
        nu = np.mean([x["av"] for x in R[lab]["hold"].values()]); pred = K * (1 - nu) / T
        nc = np.mean([x["nc"] for x in R[lab]["hold"].values()])
        mac(f"Lr{ln}{tn}Crit", ci(c)[0], "{:+.3f}"); mac(f"Lr{ln}{tn}CritCi", ci(c)[1], "{:.3f}")
        mac(f"Lr{ln}{tn}Be", ci(b)[0], "{:+.2f}"); mac(f"Lr{ln}{tn}BeCi", ci(b)[1], "{:.2f}")
        mac(f"Lr{ln}{tn}CritRule", "met" if rule(c, .5) else "not met"); mac(f"Lr{ln}{tn}BeRule", "met" if rule(b, 1.0) else "not met")
        mac(f"Lr{ln}{tn}CritNeg", int((c < 0).sum()), "{:d}")
        mac(f"Lr{ln}{tn}Pred", pred, "{:.3f}"); mac(f"Lr{ln}{tn}In", "inside" if abs(-ci(c)[0] - pred) <= ci(c)[1] else "outside")
        mac(f"Lr{ln}{tn}Avail", 100 * nu, "{:.1f}"); mac(f"Lr{ln}{tn}Nc", nc, "{:.0f}")
        mac(f"Lr{ln}{tn}NcFirst", np.mean([x["nc1"] for x in R[lab]["hold"].values()]), "{:.0f}")
        mac(f"Lr{ln}{tn}NcLate", np.mean([x["nclate"] for x in R[lab]["hold"].values()]), "{:.0f}")
        rows.append((f"10N 68E, {T} s, 24 h{'$^{\\S}$' if lab == 'asbuilt' else '$^{\\S\\ddagger}$'}", 100 * nu, nc, c, pred, b, rule(c, .5), rule(b, 1.0)))
    le = dif(R["asbuilt"]["hold"], R["launch"]["hold"], "crit"); lb = dif(R["asbuilt"]["hold"], R["launch"]["hold"], "be")
    mac(f"LrEff{tn}Crit", ci(le)[0], "{:+.3f}"); mac(f"LrEff{tn}CritCi", ci(le)[1], "{:.3f}")
    mac(f"LrEff{tn}Be", ci(lb)[0], "{:+.2f}"); mac(f"LrEff{tn}BeCi", ci(lb)[1], "{:.2f}")
with open(os.path.join(TAB, "table_long_rows.tex"), "w") as f:
    f.write("% Generated by the analysis scripts in sim/\n\\midrule\n")
    for lab, av, nc, c, pr, b, p1, p2 in rows:
        f.write(f"{lab} & {av:.1f} & {nc:.0f} & {cell(c,3)}{'$^{\\ast}$' if p1 else ''} & {sg(-pr,3)} & {cell(b)}{'$^{\\ast}$' if p2 else ''} & -- & -- & -- & --\\\\\n")
mac("RSevenRuns", n, "{:d}")
print("shas", shas, "rows", n)
with open(os.path.join(PD, "macros_long.tex"), "w") as f:
    f.write("% Generated by the analysis scripts in sim/. Do not edit by hand.\n")
    for k in sorted(M):
        f.write(f"\\newcommand{{\\{k}}}{{{M[k]}}}\n")
