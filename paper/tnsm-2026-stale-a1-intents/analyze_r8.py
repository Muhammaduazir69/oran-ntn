#!/usr/bin/env python3
"""Post hoc: A1 intents provisioned to every satellite whose feeder is up (--provisionAll), both cells,
15 and 30 s, 1 h, plus 24 h at 10N 68E. Writes macros_provisioned.tex and tables/table_prov_rows.tex."""
import csv, glob, math, os
import numpy as np
from scipy import stats
H = os.path.dirname(os.path.abspath(__file__)); PD = os.path.dirname(H); TAB = os.path.join(PD, "tables")
M = {}
def mac(k, v, f="{:.2f}"):
    if isinstance(v, str): M[k] = v; return
    s = f.format(v); M[k + "Abs"] = f.replace("+", "").format(abs(v))
    if s.startswith("-"): s = "\\ensuremath{-}" + s[1:] if any(c in "123456789" for c in s) else s[1:]
    M[k] = s
def rd(p):
    o = {}
    for d in sorted(glob.glob(p + "/seed*")):
        if d.endswith(".tmp"): continue
        r = next(csv.DictReader(open(d + "/dataplane.csv"))); S = next(csv.DictReader(open(d + "/summary.csv")))
        ou = list(csv.DictReader(open(d + "/outages.csv"))); sv = float(S["served_s"])
        o[int(d.split("seed")[-1])] = dict(crit=100 * float(r["crit_ratio"]), be=100 * float(r["be_share"]), av=float(S["feeder_avail"]),
            sha=S["binary_sha"], nc=100 * sum(float(x["dur"]) for x in ou if int(x["kind"]) in (0, 3)) / sv)
    return o
def ci(x):
    x = np.asarray(x, float); return float(x.mean()), float(stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / math.sqrt(len(x)))
def dif(A, B, k):
    s = sorted(set(A) & set(B)); return np.array([A[i][k] - B[i][k] for i in s])
def sg(x, nd=2):
    t = f"{x:+.{nd}f}"; return f"{0:.{nd}f}" if float(t) == 0 else t.replace("-", "$-$")
def cell(x, nd=2):
    m, h = ci(x); return f"{sg(m, nd)}$\\pm${h:.{nd}f}"
def rule(x, thr):
    m, h = ci(x); return m <= -thr and m + h < 0 and (x < 0).sum() >= 0.8 * len(x)
K = 8.8; rows = []; shas = set(); n = 0
for site, sn, slab in (("base", "Base", "20N 64E"), ("lo", "Lo", "10N 68E")):
    for T, tn in ((15, "Fifteen"), (30, "Thirty")):
        P = {a: rd(f"{H}/runs/r8/prov_{site}_ta{T}/{a}") for a in ("control", "hold", "env02", "wccontrol", "wchold", "wcenv02")}
        R5 = {a: rd(f"{H}/runs/r5/{site}_ta{T}/{a}") for a in ("control", "hold")}
        for X in P.values(): shas |= {x["sha"] for x in X.values()}; n += len(X)
        k = f"Pv{sn}{tn}"
        c = dif(P["hold"], P["control"], "crit"); b = dif(P["hold"], P["control"], "be")
        wc = dif(P["wchold"], P["wccontrol"], "crit"); wb = dif(P["wchold"], P["wccontrol"], "be")
        ec = dif(P["env02"], P["hold"], "crit"); eb = dif(P["env02"], P["hold"], "be")
        wec = dif(P["wcenv02"], P["wchold"], "crit"); web = dif(P["wcenv02"], P["wchold"], "be")
        pv = dif(P["hold"], R5["hold"], "crit"); pvb = dif(P["hold"], R5["hold"], "be")  # provisioned minus serving-only hold
        nu = np.mean([x["av"] for x in P["hold"].values()]); pred = K * (1 - nu) / T
        for nm, x, nd in (("Crit", c, 3), ("Be", b, 2), ("WcCrit", wc, 3), ("WcBe", wb, 2), ("EnvCrit", ec, 3), ("EnvBe", eb, 2),
                          ("WcEnvCrit", wec, 3), ("WcEnvBe", web, 2), ("VsServ", pv, 3), ("VsServBe", pvb, 2)):
            mac(k + nm, ci(x)[0], "{:+." + str(nd) + "f}"); mac(k + nm + "Ci", ci(x)[1], "{:." + str(nd) + "f}")
        mac(k + "CritNeg", int((c < 0).sum()), "{:d}")
        mac(k + "CritRule", "met" if rule(c, .5) else "not met"); mac(k + "BeRule", "met" if rule(b, 1.0) else "not met")
        mac(k + "WcBeRule", "met" if rule(wb, 1.0) else "not met")
        mac(k + "Pred", pred, "{:.3f}"); mac(k + "In", "inside" if abs(-ci(c)[0] - pred) <= ci(c)[1] else "outside")
        mac(k + "Avail", 100 * nu, "{:.1f}"); mac(k + "Nc", np.mean([x["nc"] for x in P["hold"].values()]), "{:.0f}")
        rows.append((f"{slab}, {T} s$^{{\\P}}$", 100 * nu, np.mean([x["nc"] for x in P["hold"].values()]), c, pred, b, ec, eb, wc, wb, rule(c, .5), rule(b, 1.0), rule(wb, 1.0)))
# 24 h, 10N 68E
for T, tn in ((15, "Fifteen"), (30, "Thirty")):
    L = {a: rd(f"{H}/runs/r8/provlong_lo_ta{T}/{a}") for a in ("control", "hold")}
    for X in L.values(): shas |= {x["sha"] for x in X.values()}; n += len(X)
    if not L["hold"]: continue
    c = dif(L["hold"], L["control"], "crit"); b = dif(L["hold"], L["control"], "be")
    mac(f"PvLong{tn}Crit", ci(c)[0], "{:+.3f}"); mac(f"PvLong{tn}CritCi", ci(c)[1], "{:.3f}")
    mac(f"PvLong{tn}Be", ci(b)[0], "{:+.2f}"); mac(f"PvLong{tn}BeCi", ci(b)[1], "{:.2f}")
    mac(f"PvLong{tn}N", len(c), "{:d}"); mac(f"PvLong{tn}CritNeg", int((c < 0).sum()), "{:d}")
with open(os.path.join(TAB, "table_prov_rows.tex"), "w") as f:
    f.write("% Generated by the analysis scripts in sim/\n\\midrule\n")
    for lab, av, nc, c, pr, b, ec, eb, wc, wb, p1, p2, p3 in rows:
        st = lambda p: "$^{\\ast}$" if p else ""
        f.write(f"{lab} & {av:.1f} & {nc:.0f} & {cell(c,3)}{st(p1)} & {sg(-pr,3)} & {cell(b)}{st(p2)} & {cell(ec,3)} & {cell(eb)} & -- & --\\\\\n")
mac("RlEightRuns", n, "{:d}")
mac("PostHocRuns", n + len(glob.glob(f"{H}/runs/r6/*/*/seed*")) + len(glob.glob(f"{H}/runs/r7/*/*/seed*")), "{:d}"); mac("ProvHash", "959bfda8edb1f5ab")
print("shas", shas, "rows", n)
with open(os.path.join(PD, "macros_provisioned.tex"), "w") as f:
    f.write("% Generated by the analysis scripts in sim/. Do not edit by hand.\n")
    for k in sorted(M):
        f.write(f"\\newcommand{{\\{k}}}{{{M[k]}}}\n")
