#!/usr/bin/env python3
"""Round 5: a low-availability site against the base cell. Rule per row, the critical law out of sample,
never-contacted time, static envelope. Writes macros_sites.tex and tables/table_sites_dp.tex."""
import csv, glob, math, os
import numpy as np
from scipy import stats
H = os.path.dirname(os.path.abspath(__file__)); PD = os.path.dirname(H); TAB = os.path.join(PD, "tables")
M = {}
def mac(k, v, f="{:.2f}"):
    if isinstance(v, str): M[k] = v; return
    s = f.format(v); M[k + "Abs"] = f.replace("+", "").format(abs(v))
    if s.startswith("-"): s = "\\ensuremath{-}" + s[1:] if any(c in "123456789" for c in s) else s[1:]
    M[k] = s
def rd(path):
    o = {}
    for d in sorted(glob.glob(path + "/seed*")):
        if d.endswith(".tmp"): continue
        r = {k: float(v) for k, v in next(csv.DictReader(open(d + "/dataplane.csv"))).items()}
        S = next(csv.DictReader(open(d + "/summary.csv")))
        ou = list(csv.DictReader(open(d + "/outages.csv")))
        sv = float(S["served_s"])
        r.update(av=float(S["feeder_avail"]), sha=S["binary_sha"], crit=100 * r["crit_ratio"], be=100 * r["be_share"],
                 nc=100 * sum(float(x["dur"]) for x in ou if int(x["kind"]) in (0, 3)) / sv)
        o[int(d.split("seed")[-1])] = r
    return o
def ci(x):
    x = np.asarray(x, float); return float(x.mean()), float(stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / math.sqrt(len(x)))
def dif(A, B, k):
    s = sorted(set(A) & set(B)); return np.array([A[i][k] - B[i][k] for i in s])
def sg(x, nd=2):
    t = f"{x:+.{nd}f}"
    return f"{0:.{nd}f}" if float(t) == 0 else t.replace("-", "$-$")
def cell(x, nd=2):
    m, h = ci(x); return f"{sg(m, nd)}$\\pm${h:.{nd}f}"
def rule(x, thr):
    m, h = ci(x); return m <= -thr and m + h < 0 and (x < 0).sum() >= 0.8 * len(x)
K = 8.8
rows = []; shas = set()
for site, slab, tg in [("base", "20N 64E", "Base"), ("lo", "10N 68E", "Lo")]:
    for T in (15, 30):
        A = {a: rd(f"{H}/runs/r5/{site}_ta{T}/{a}") for a in ["control", "hold", "env02", "wccontrol", "wcstatic", "wcfixed"]}
        for a in A.values():
            shas |= {x["sha"] for x in a.values()}
        nu = np.mean([x["av"] for x in A["hold"].values()])
        nc = np.mean([x["nc"] for x in A["hold"].values()])
        c = dif(A["hold"], A["control"], "crit"); b = dif(A["hold"], A["control"], "be")
        ec = dif(A["env02"], A["hold"], "crit"); eb = dif(A["env02"], A["hold"], "be")
        sc = dif(A["wcstatic"], A["wccontrol"], "crit")
        fx = dif(A["wcfixed"], A["wccontrol"], "crit")
        fh = dif(A["wcfixed"], A["hold"], "crit")
        pred = K * (1 - nu) / T
        rows.append(dict(fx=fx, lab=f"{slab}, {T} s", nu=100 * nu, nc=nc, c=c, b=b, ec=ec, eb=eb, sc=sc, pred=pred, p1=rule(c, .5), p2=rule(b, 1.0)))
        t = f"{tg}{'Fifteen' if T == 15 else 'Thirty'}"
        mac(f"Ste{t}Avail", 100 * nu, "{:.1f}"); mac(f"Ste{t}Nc", nc, "{:.0f}")
        for k, x, nd in [("Crit", c, 3), ("Be", b, 2), ("EnvCrit", ec, 3), ("EnvBe", eb, 2), ("StaticCrit", sc, 3), ("FixedCrit", fx, 3), ("FixedHoldCrit", fh, 3)]:
            mac(f"Ste{t}{k}", ci(x)[0], "{:+." + str(nd) + "f}"); mac(f"Ste{t}{k}Ci", ci(x)[1], "{:." + str(nd) + "f}")
        mac(f"Ste{t}Pred", pred, "{:.3f}")
        mac(f"Ste{t}CritRule", "met" if rows[-1]["p1"] else "not met", "{}"); mac(f"Ste{t}BeRule", "met" if rows[-1]["p2"] else "not met", "{}")
_T = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tables")
def _rows(name):
    q = os.path.join(_T, name)
    return "".join(l for l in open(q) if not l.startswith("%")) if os.path.exists(q) else ""
HEAD = ("% Generated by the analysis scripts in sim/\n\\begin{tabular}{@{}lrrrrrrrrr@{}}\n\\toprule\n"
        "Cell, $T_{\\mathrm{A1}}$ & Avail. & Never-cont. & Hold: crit. & Law & Hold: BE & Lease: crit. & Lease: BE & Static & Fixed$^{\\dagger}$\\\\\n"
        " & (\\%) & (\\% served) & (points) & (points) & (points) & (points) & (points) & (WC) & (WC)\\\\\n")
with open(os.path.join(TAB, "table_sites_dp.tex"), "w") as f:
    f.write(HEAD + "\\midrule\n")
    for R in rows:
        f.write(f"{R['lab']} & {R['nu']:.1f} & {R['nc']:.0f} & {cell(R['c'],3)}{'$^{\\ast}$' if R['p1'] else ''} & {sg(-R["pred"],3)} & {cell(R['b'])}{'$^{\\ast}$' if R['p2'] else ''} & {cell(R['ec'],3)} & {cell(R['eb'])} & {cell(R['sc'],3)} & {cell(R['fx'],3)}\\\\\n")
    f.write(_rows("table_prov_rows.tex"))
    f.write("\\bottomrule\n\\end{tabular}\n")
with open(os.path.join(TAB, "table_launch_long.tex"), "w") as f:
    f.write(HEAD + _rows("table_launch_rows.tex").lstrip() if False else HEAD)
    body = _rows("table_launch_rows.tex") + _rows("table_long_rows.tex")
    f.write(body)
    f.write("\\bottomrule\n\\end{tabular}\n")
inn = sum(abs(-ci(R["c"])[0] - R["pred"]) <= ci(R["c"])[1] for R in rows)
mac("SteLawIn", inn, "{:d}"); mac("SteN", len(rows), "{:d}")
mac("SteLawMaxErr", max(abs(-ci(R["c"])[0] - R["pred"]) for R in rows), "{:.3f}")
mac("SteCritPass", sum(R["p1"] for R in rows), "{:d}"); mac("SteBePass", sum(R["p2"] for R in rows), "{:d}")
mac("SteRuns", sum(len(glob.glob(f"{H}/runs/r5/*/{a}/seed*")) for a in ["control", "hold", "env02", "wccontrol", "wcstatic", "wcfixed"]), "{:d}")
# boundary from the law: critical loss reaches 0.5 when (1 - nu) / D >= 0.5 / K
mac("BoundRate", 0.5 / K, "{:.3f}")
mac("BoundAvailFifteen", 100 * (1 - 0.5 / K * 15), "{:.0f}"); mac("BoundAvailThirty", 100 * (1 - 0.5 / K * 30), "{:.0f}")
print("shas", shas)
with open(os.path.join(PD, "macros_sites.tex"), "w") as f:
    f.write("% Generated by the analysis scripts in sim/. Do not edit by hand.\n")
    for k in sorted(M):
        f.write(f"\\newcommand{{\\{k}}}{{{M[k]}}}\n")
